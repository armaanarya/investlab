@dataclass(frozen=True, slots=True)
class WhartonProfile:
    """A `CompetitionProfile` for the Wharton Investment Network Simulation.

    Two states, encoded by whether `season` is set:

    - `WHARTON_UNVERIFIED` (`season is None`, the default): the 2026-27
      trading rules have not been released. Prior-season (2025-26) values
      load as PROVISIONAL. `check_rules` reports exactly what is missing
      and names the 2026-09-15 release date. `evaluate`/`is_eligible` still
      run -- research screening never stops -- but every ETF is blocked
      pending the Approved ETF List, and `build_daily_plan` withholds every
      order rather than emit an actionable sheet under unread rules.
    - `WHARTON_VERIFIED` (`season` set via `with_season`): a
      `WhartonSeasonConfig` supplies 2026-27 starting capital, the Approved
      ETF List, the position ceiling, the minimum-activity deadline, and
      the client mandate summary.
    """

    season: WhartonSeasonConfig | None = None
    budget: TradeBudget = field(default_factory=TradeBudget)

    name: ClassVar[str] = "wharton"
    display_name: ClassVar[str] = "Wharton Investment Network Simulation (WInS)"
    allows_margin: ClassVar[bool] = False
    allows_shorting: ClassVar[bool] = False
    commission_per_trade: ClassVar[Decimal] = PROVISIONAL_STOCK_COMMISSION
    treasury_commission_per_trade: ClassVar[Decimal] = PROVISIONAL_TREASURY_COMMISSION
    min_share_price: ClassVar[Decimal] = PROVISIONAL_MIN_SHARE_PRICE

    # -- identity / state ---------------------------------------------------

    @property
    def status(self) -> SeasonStatus:
        return SeasonStatus.WHARTON_VERIFIED if self.season else SeasonStatus.WHARTON_UNVERIFIED

    @property
    def is_verified(self) -> bool:
        return self.season is not None

    @property
    def starting_cash(self) -> Decimal:
        return self.season.starting_capital if self.season else PROVISIONAL_STARTING_CAPITAL

    @property
    def starting_cash_is_provisional(self) -> bool:
        return self.season is None

    @property
    def position_ceiling_fraction(self) -> Decimal:
        return (
            self.season.position_ceiling_fraction if self.season else SELF_IMPOSED_POSITION_CEILING
        )

    # -- state transitions ---------------------------------------------------

    def with_season(self, season: WhartonSeasonConfig) -> WhartonProfile:
        return replace(self, season=season)

    def with_trade_budget(self, budget: TradeBudget) -> WhartonProfile:
        return replace(self, budget=budget)

    # -- eligibility ----------------------------------------------------------

    def evaluate(self, instrument: Instrument, bar: Bar) -> BlockedOrder | None:
        """Check order, first match wins, chosen so the reported reason is
        the most fundamental one: commodity/crypto trust -> leveraged/
        inverse -> unsupported asset class -> missing exchange -> ETF
        approval -> bond approval -> price floor.
        """
        symbol = instrument.symbol

        if instrument.is_commodity_or_crypto_trust:
            grounds = ["explicitly prohibited: crypto and commodity trusts are banned outright"]
            if instrument.asset_class is AssetClass.ETF:
                grounds.append(
                    "ETFs are eligible only from the Approved ETF List, which this "
                    "instrument is not on"
                )
            if len(grounds) > 1:
                detail = (
                    f"{symbol} is rejected on two independent grounds: "
                    f"(1) {grounds[0]}; (2) {grounds[1]}."
                )
            else:
                detail = f"{symbol} is rejected: {grounds[0]}."
            return BlockedOrder(symbol, BlockReason.PROHIBITED_SECURITY, detail)

        if instrument.is_leveraged:
            return BlockedOrder(
                symbol,
                BlockReason.PROHIBITED_SECURITY,
                f"{symbol} is a leveraged/inverse product; Wharton prohibits "
                "derivatives and leveraged instruments.",
            )

        # `AssetClass` has no DERIVATIVE member, so a true option or future
        # cannot reach this function at all; leveraged/inverse products are
        # the closest representable proxy and are rejected above. This
        # check is written as an allow-list (stock/ETF/bond only) rather
        # than a deny-list, so any future AssetClass member is rejected by
        # default instead of silently passing through.
        if instrument.asset_class not in (AssetClass.STOCK, AssetClass.ETF, AssetClass.BOND):
            return BlockedOrder(
                symbol,
                BlockReason.PROHIBITED_SECURITY,
                f"{symbol} is a {instrument.asset_class.value}, not an eligible "
                "Wharton asset class (stock, ETF, or treasury bond).",
            )

        if not instrument.exchange:
            return BlockedOrder(
                symbol,
                BlockReason.INELIGIBLE_EXCHANGE,
                f"{symbol} has no listed exchange; Wharton requires a platform-supported exchange.",
            )

        if instrument.asset_class is AssetClass.ETF:
            if self.season is None:
                return BlockedOrder(
                    symbol,
                    BlockReason.UNVERIFIED_INSTRUMENT,
                    f"{symbol}: the Approved ETF List is not yet known. It "
                    f"arrives with the {MATERIALS_RELEASE.isoformat()} materials "
                    "release; until then every ETF is blocked.",
                )
            if symbol not in self.season.approved_etfs:
                return BlockedOrder(
                    symbol,
                    BlockReason.PROHIBITED_SECURITY,
                    f"{symbol} is not on the Approved ETF List for the 2026-27 season.",
                )

        # Treasury bonds are also drawn from an approved list per the rules,
        # but that list is optional and is not one of the five
        # WhartonSeasonConfig keys this profile carries -- see the report
        # for this observation. Bonds are accepted here subject only to the
        # price floor below.

        if bar.close < self.min_share_price:
            return BlockedOrder(
                symbol,
                BlockReason.PRICE_BELOW_MINIMUM,
                f"{symbol} at ${bar.close} is below the PROVISIONAL $5 minimum share price.",
            )

        return None

    def is_eligible(self, instrument: Instrument, bar: Bar) -> tuple[bool, str]:
        blocked = self.evaluate(instrument, bar)
        if blocked is None:
            return True, ""
        return False, blocked.detail

    # -- sizing -----------------------------------------------------------

    def sizing_constraints(self, account: AccountState) -> SizingConstraints:
        return SizingConstraints(
            equity=account.equity,
            spendable_cash=account.cash,  # margin banned: cash only, never buying power
            risk_fraction=SELF_IMPOSED_RISK_FRACTION,
            position_ceiling_fraction=self.position_ceiling_fraction,
            min_shares=1,
            min_price=self.min_share_price,
            commission_per_trade=self.commission_per_trade,
            sell_fee_rate=Decimal("0"),
        )

    # -- rule checks --------------------------------------------------------

    def check_rules(self, account: AccountState, today: date) -> list[RuleCheck]:
        checks: list[RuleCheck] = []

        if self.season is None:
            missing = (
                "starting capital, the Approved ETF List, the client mandate, "
                "position limits, and the minimum trading activity deadline"
            )
            checks.append(
                RuleCheck(
                    "season_materials_verified",
                    RuleStatus.INCOMPLETE,
                    False,
                    (
                        "2026-27 Wharton trading rules are not yet released "
                        f"(materials arrive {MATERIALS_RELEASE.isoformat()}). "
                        f"Missing: {missing}. Values shown are PROVISIONAL, "
                        "carried over from the 2025-26 season. Starting capital "
                        f"defaults to $500,000, PROVISIONAL -- NOT the "
                        f"${MISREPORTED_STARTING_CAPITAL:,} figure in "
                        "StockTrak's boilerplate FAQ, which is wrong for this "
                        "competition."
                    ),
                    deadline=MATERIALS_RELEASE,
                )
            )
            checks.append(
                RuleCheck(
                    "trading_rules_loaded",
                    RuleStatus.VERIFIED,
                    False,
                    (
                        "No order sheet can be marked actionable until a "
                        "WhartonSeasonConfig for 2026-27 is loaded with "
                        "`with_season`. This is a confirmed rule: do not trade "
                        "under season parameters that have not been read."
                    ),
                )
            )
        else:
            checks.append(
                RuleCheck(
                    "season_materials_verified",
                    RuleStatus.VERIFIED,
                    True,
                    f"2026-27 season config loaded from {self.season.source}.",
                )
            )
            checks.append(
                RuleCheck(
                    "trading_rules_loaded",
                    RuleStatus.VERIFIED,
                    True,
                    "2026-27 trading rules loaded; order sheet may be actionable.",
                )
            )

        checks.append(self._approved_etf_minimum_check(account))
        checks.append(self.budget.to_rule_check(account.equity))
        checks.append(self._minimum_trading_activity_check(today))
        checks.append(self._commission_drag_check(account))
        checks.append(self._margin_and_shorting_check(account))
        checks.append(
            RuleCheck(
                "student_authorship",
                RuleStatus.VERIFIED,
                True,
                (
                    "Wharton requires original student work: trading notes, "
                    "the Investment Policy Statement, and the investment "
                    "thesis must be written by the student, not generated by "
                    "this tool. Any AI assistance used must be cited in APA in "
                    "the Works Cited. This module emits only facts, numbers, "
                    "and rule status."
                ),
            )
        )

        return checks

    def _approved_etf_minimum_check(self, account: AccountState) -> RuleCheck:
        if self.season is None:
            return RuleCheck(
                "approved_etf_minimum",
                RuleStatus.INCOMPLETE,
                False,
                (
                    "Cannot verify the at-least-one-approved-ETF requirement: "
                    f"the Approved ETF List has not been released (arrives "
                    f"{MATERIALS_RELEASE.isoformat()})."
                ),
            )
        held_symbols = {pos.symbol for pos in account.positions if pos.quantity > 0}
        held_approved = sorted(held_symbols & self.season.approved_etfs)
        has_approved_etf = bool(held_approved)
        return RuleCheck(
            "approved_etf_minimum",
            RuleStatus.VERIFIED,
            has_approved_etf,
            (
                "At least one Approved-ETF-List holding is required. "
                + (
                    f"Satisfied: currently holding {held_approved} from the Approved ETF List."
                    if has_approved_etf
                    else "Not yet satisfied: no Approved-ETF-List holding in this account."
                )
            ),
        )

    def _minimum_trading_activity_check(self, today: date) -> RuleCheck:
        deadline = (
            self.season.minimum_activity_deadline if self.season else PROVISIONAL_ACTIVITY_DEADLINE
        )
        satisfied = self.budget.trades_used >= 1
        provisional_note = "" if self.season else " (PROVISIONAL deadline, 2025-26 season)"
        detail = (
            f"At least one executed trade is required by {deadline.isoformat()}"
            f"{provisional_note}. "
            + (
                "Satisfied: a trade has been recorded."
                if satisfied
                else "Not yet satisfied: no trade has been recorded yet."
            )
        )
        return RuleCheck(
            "minimum_trading_activity", RuleStatus.VERIFIED, satisfied, detail, deadline=deadline
        )

    def _commission_drag_check(self, account: AccountState) -> RuleCheck:
        equity = account.equity
        if equity <= 0:
            return RuleCheck(
                "commission_drag",
                RuleStatus.VERIFIED,
                True,
                (
                    f"Commission spent so far: ${self.budget.commission_spent:,.2f} "
                    f"({self.budget.trades_used} trades at PROVISIONAL "
                    f"${self.budget.commission_per_trade}/trade). Equity is not "
                    "positive, so drag as a percentage of equity is not "
                    "computable."
                ),
            )
        pct = self.budget.commission_drag_pct(equity)
        return RuleCheck(
            "commission_drag",
            RuleStatus.VERIFIED,
            True,
            (
                f"Commission spent so far: ${self.budget.commission_spent:,.2f} "
                f"on {self.budget.trades_used} trades (PROVISIONAL "
                f"${self.budget.commission_per_trade}/trade) is a {pct:.2f}% "
                f"drag on ${equity:,.2f} equity."
            ),
        )

    def _margin_and_shorting_check(self, account: AccountState) -> RuleCheck:
        problems = []
        if account.liabilities > 0:
            problems.append(
                f"margin liability of ${account.liabilities:,.2f} detected; "
                "Wharton bans margin outright"
            )
        shorts = sorted(pos.symbol for pos in account.positions if pos.quantity < 0)
        if shorts:
            problems.append(
                f"short position(s) detected in {', '.join(shorts)}; Wharton "
                "bans short selling outright"
            )
        if problems:
            return RuleCheck(
                "margin_and_shorting_ban",
                RuleStatus.VERIFIED,
                False,
                "VIOLATION: " + "; ".join(problems) + ". These are errors, not warnings.",
            )
        return RuleCheck(
            "margin_and_shorting_ban",
            RuleStatus.VERIFIED,
            True,
            "No margin liability and no short positions detected; margin and "
            "shorting are banned outright by the rules.",
        )

    # -- execution ----------------------------------------------------------

    def execution_note(self, today: date) -> str:
        """One line telling the student when and how orders will fill.

        Wharton is REAL TIME during market hours -- the opposite of DECA,
        which prices every fill at that session's close regardless of when
        the order was entered.
        """
        parts = [
            (
                "Wharton WInS executes REAL TIME during market hours "
                "(9:30a-4:00p ET); displayed prices lag the live tape by 10-15 "
                "minutes, after-hours orders fill at the next trading day's "
                "open, and international equities and bonds price end-of-day "
                "-- the opposite of DECA, which prices every fill at that "
                "session's close regardless of when the order was entered."
            )
        ]
        if today < TRADING_BEGINS:
            parts.append(f"Trading has not opened yet: it begins {TRADING_BEGINS.isoformat()}.")
        return " ".join(parts)

    def execution_note_lines(self, today: date) -> tuple[str, ...]:
        """The same content as `execution_note`, split into bullet lines for
        callers that want a multi-line rendering."""
        lines = [
            ("Wharton WInS is REAL TIME during market hours: live fills 9:30a-4:00p ET."),
            "Displayed prices lag the live tape by 10-15 minutes.",
            "Orders entered after-hours fill at the next trading day's open.",
            "International equities and bonds price end-of-day, not real time.",
            (
                "Contrast with DECA: DECA prices every fill at that session's "
                "close, regardless of when the order was entered."
            ),
        ]
        if today < TRADING_BEGINS:
            lines.append(f"Trading has not opened yet: it begins {TRADING_BEGINS.isoformat()}.")
        return tuple(lines)


def build_daily_plan(
    profile: WhartonProfile,
    account: AccountState,
    today: date,
    orders: tuple[SizedOrder, ...] = (),
    blocked: tuple[BlockedOrder, ...] = (),
    data_is_stale: bool = False,
    notes: tuple[str, ...] = (),
) -> DailyPlan:
    """Assemble the daily order sheet.

    In `WHARTON_UNVERIFIED`, every proposed order is withheld: it moves into
    `blocked` with `BlockReason.RULE_CONFLICT` naming the 2026-09-15
    release date, so a non-actionable plan is also an empty order sheet.
    Eligibility screening (`is_eligible`/`evaluate`) is unaffected and can
    still be called directly regardless of this gate.
    """
    rule_checks = profile.check_rules(account, today)
    emitted_orders = orders
    extra_blocked: tuple[BlockedOrder, ...] = ()

    if profile.season is None:
        extra_blocked = tuple(
            BlockedOrder(
                order.symbol,
                BlockReason.RULE_CONFLICT,
                (
                    f"{order.symbol}: no order sheet can be marked actionable "
                    "before the 2026-27 Wharton trading rules are released "
                    f"({MATERIALS_RELEASE.isoformat()}). Order withheld "
                    "pending verification."
                ),
            )
            for order in orders
        )
        emitted_orders = ()

    return DailyPlan(
        profile=profile.name,
        as_of=today,
        data_is_stale=data_is_stale,
        account=account,
        orders=emitted_orders,
        blocked=blocked + extra_blocked,
        rule_checks=tuple(rule_checks),
        notes=notes,
    )
