"""Wharton Investment Network Simulation (WInS) competition profile.

The 2026-27 Wharton trading rules are not released until 2026-09-15. This
module therefore has two states:

- `SeasonStatus.WHARTON_UNVERIFIED` (the default): no 2026-27 config has been
  loaded. Every dollar figure and list shown is PROVISIONAL, carried over
  from the 2025-26 season (see `docs/rules/wharton-verified.md`). ETFs are
  blocked outright because the Approved ETF List does not exist yet.
  `check_rules` reports exactly what is missing and names 2026-09-15.
  `build_daily_plan` refuses to emit an actionable order sheet, though
  eligibility screening keeps running.
- `SeasonStatus.WHARTON_VERIFIED`: reached by loading a `WhartonSeasonConfig`
  (via `load_season_config` + `WhartonProfile.with_season`) once a student
  has transcribed the 2026-09-15 materials.

AI-authorship constraint (Wharton: "You may not submit any work generated by
an AI program as your own"; trading notes are audited). This module emits
only facts, numbers, constraint results, and rule status. It never
generates an investment thesis, trading-note text, Investment Policy
Statement prose, or any other narrative a student would submit. Where a
config field is transcribed by a student verbatim (`client_mandate_summary`)
this module stores and echoes it; it never writes or edits it.

Money is always `decimal.Decimal`. A `float` literal in a money path here is
a defect. Imports: `investlab.contracts` and the standard library only.
"""

